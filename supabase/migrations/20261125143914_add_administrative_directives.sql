-- Persist administrative directions and responses between the director and chair.
CREATE TABLE public.administrative_directives (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content text NOT NULL CHECK (char_length(btrim(content)) BETWEEN 1 AND 4000),
  teacher_id bigint REFERENCES public.teachers(id) ON DELETE SET NULL,
  teacher_name text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'in_progress', 'completed')),
  response text NOT NULL DEFAULT '' CHECK (char_length(response) <= 4000),
  created_by bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
  updated_by bigint REFERENCES public.app_users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX administrative_directives_created_at_idx
  ON public.administrative_directives (created_at DESC);
CREATE INDEX administrative_directives_teacher_id_idx
  ON public.administrative_directives (teacher_id);

ALTER TABLE public.administrative_directives ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.administrative_directives FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.administrative_directives TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.administrative_directives_id_seq TO service_role;