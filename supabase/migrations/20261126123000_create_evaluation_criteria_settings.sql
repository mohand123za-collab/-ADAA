-- Configurable evaluation criteria managed by the director.
CREATE TABLE public.evaluation_criteria_settings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  criterion_key text NOT NULL UNIQUE CHECK (criterion_key ~ '^[a-z][a-z0-9_]{1,48}$'),
  label text NOT NULL CHECK (char_length(btrim(label)) BETWEEN 1 AND 200),
  max_score numeric(5,2) NOT NULL CHECK (max_score > 0 AND max_score <= 100),
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

